 % ========================================================================
 % 文件名：npf_cumulative.m
 % 作用：计算 Neukum 生产函数 NPF 在指定直径处的累积密度 N(>D)。
 % 通俗原理：月球上不同大小的撞击坑数量有一个稳定的“比例关系”。
 %       把直径取对数，再用 11 次多项式近似这个关系，就可以算出
 %       “直径大于 D 的坑，单位面积平均有多少个”。
 % 输入：D_km 直径（km）；coeff 12 个多项式系数，从常数项到 11 次项。
 % 输出：N 与 D_km 同形状的累积密度（km^-2）。
 % 关键步骤：polyval 需要最高次在前，所以先 fliplr 再计算。
 % ========================================================================
 function N = npf_cumulative(D_km, coeff) % 函数声明：计算给定直径处的累积密度 N(>D)
 %NPF_CUMULATIVE Neukum 生产函数的累积密度 N(>D)
 %
 % 输入
 % D_km : 直径，单位 km（标量或列向量，元素需 > 0）
 % coeff : 1x12 系数 [a0 a1 ... a11]
 % 输出
 % N : 与 D_km 同形的累积密度，单位与编目一致（km^-2）
 %
 % 说明：多项式按 x = log10(D/km) 展开，量级对应 1 Ga 参考表面。
 % 与年代函数联用时必须按 s04_model 中的归一化关系除以 CF(1 Ga)。

 x = log10(D_km(:)); % 把直径换算成以 10 为底的对数
 p = fliplr(coeff);      % polyval 需要从最高次到常数项
 N = 10.^polyval(p, x); % 用多项式求对数密度，再取 10 的幂还原
 N = reshape(N, size(D_km)); % 把结果恢复成与输入相同的矩阵形状
 end % 函数结束
