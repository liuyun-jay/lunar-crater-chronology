 % ========================================================================
 % 文件名：model_csfd.m
 % 作用：给定一个年龄 T，计算模型预测的累积尺寸-频率分布 N(>D)。
 % 通俗原理：先查“1 亿年标准表面”在不同直径处应有多少坑，再根据年龄
 %       放大或缩小这个数量。年龄越老，单位面积上的坑越多。
 % 关键公式：N(D,T) = NPF(D) × CF(T) / CF(1 Ga)。
 %       除以 CF(1 Ga) 是为了把生产函数和年代函数对齐到同一基准。
 % 输入：D_km 直径；T_Ga 年龄；model 由 s04_model.m 返回的系数。
 % 输出：N 模型累积密度（km^-2）。
 % ========================================================================
 function N = model_csfd(D_km, T_Ga, model) % 函数声明：给定年龄计算模型累积密度
 %MODEL_CSFD 给定年龄下的模型累积尺寸-频率分布 N(>D, T)
 %
 % N_model(D,T) = NPF(D) * CF(T) / CF(1 Ga)
 %
 % 归一化因子是本文最容易被忽略、也最容易导致年龄系统性偏移的一步：
 % 生产函数多项式本身对应 1 Ga 参考表面，若直接乘以 CF(T) 会低估模型密度
 % 约 3 个数量级，反演出的年龄将严重偏大。

 N = npf_cumulative(D_km, model.npf_coeff) .* (model.CF(T_Ga) ./ model.CF_1Ga); % NPF 密度乘以 CF(T)/CF(1 Ga) 完成
 归一化
 end % 结束模型 CSFD 计算
