 % ========================================================================
 % 文件名：synthesize_craters.m
 % 作用：给定已知年龄，生成一批符合模型统计规律的假撞击坑直径。
 % 通俗原理：先用泊松分布随机决定“总共有几个坑”，再根据模型 CSFD 的
 %       概率形状给每个坑随机分配直径。这样生成的假数据带有和真实
 %       观测相同的随机波动，可用于检验反演程序是否正确。
 % 输入：T_Ga 设定年龄；area_km2；Dlo/Dhi 直径范围；model 模型。
 % 输出：D 合成撞击坑直径向量。
 % 关键：直径抽样必须按 CSFD 形状，不能假设成简单幂律。
 % ========================================================================
 function D = synthesize_craters(T_Ga, area_km2, Dlo, Dhi, model) % 函数声明：按模型 CSFD 生成合成直径
 %SYNTHESIZE_CRATERS 由模型 CSFD 抽样生成合成撞击坑直径（用于自检）
 %
 % 步骤：
 % 1) 期望总坑数 = N(>Dlo) * A，按泊松分布抽样得到实际坑数；
 % 2) 直径在 [Dlo, Dhi] 上按模型的截断累积分布做逆变换抽样。
 %
 % 注意：抽样必须基于 N(>D) 的"形状"，不能简单假设幂律，

% 否则自检本身就偏离了真实模型，失去检验意义。

Dgrid = logspace(log10(Dlo), log10(Dhi), 4000)'; % 在对数等距网格上采样直径
Ntot = model_csfd(Dgrid, T_Ga, model); % 计算该年龄下网格点的模型累积密度

Nlo = Ntot(1); % 直径下限处的累积密度 N(>Dlo)
Nhi = Ntot(end); % 直径上限处的累积密度 N(>Dhi)

n_sim = rnd_poisson(Nlo * area_km2); % 期望坑数 N(>Dlo)×A 按泊松抽样
if n_sim == 0 % 抽到 0 个坑时返回空编目
   D = []; % 返回空直径数组
   return; % 提前返回，跳过直径抽样
end % 结束零坑判断

F = (Nlo - Ntot) / (Nlo - Nhi);   % 截断区间上的累积分布
F = max(min(F, 1), 0); % 把逆变换概率截断到 [0,1] 防越界
[F, ia] = unique(F, 'first');   % 去重，保证单调可插值
Dg = Dgrid(ia); % 取去重后对应的直径网格

u = rand(n_sim, 1); % 生成均匀随机数作为分位点
logD = interp1(F, log10(Dg), u, 'linear', 'extrap'); % 按截断分布逆变换抽样对数直径
D = 10.^logD; % 取幂还原为直径（km）
D = D(D >= Dlo & D <= Dhi); % 剔除极少数越界样本
end % 结束合成编目生成函数
